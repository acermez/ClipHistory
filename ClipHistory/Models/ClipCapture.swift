import CryptoKit
import Foundation
import ImageIO
import UniformTypeIdentifiers

enum PasteboardTypes {
    static let text = "public.utf8-plain-text"
    static let rtf = "public.rtf"
    static let html = "public.html"
    static let png = "public.png"
    static let tiff = "public.tiff"
    static let jpeg = "public.jpeg"
    static let fileURL = "public.file-url"
    static let url = "public.url"

    /// The flavors we save. Others (app-private formats) are dropped.
    static let kept = [text, rtf, html, png, tiff, jpeg, fileURL, url]
    static let images = [png, tiff, jpeg]

    /// Markers that apps put on the pasteboard to say "don't record this"
    /// (see nspasteboard.org). Password managers use the concealed one.
    static let skipMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]
}

/// A clipboard snapshot that is ready to be stored.
struct CapturedClip {
    var payload: ClipPayload
    var kind: ClipKind
    var title: String
    var searchText: String
    var hash: String
    var byteSize: Int
    var imageWidth: Int?
    var imageHeight: Int?
    var fileCount: Int?
    var isDirectory: Bool?
    /// Raw image data used to make the thumbnail (image items only).
    var imageData: Data?
}

enum ClipCapture {
    static let maxBytes = 50 * 1024 * 1024
    static let maxSearchLength = 5_000
    static let maxTitleLength = 300

    static func shouldSkip(types: [String]) -> Bool {
        types.contains { PasteboardTypes.skipMarkers.contains($0) }
    }

    /// Turns raw pasteboard data into a storable clip, or nil when there is
    /// nothing worth keeping (empty, whitespace only, too large, unknown).
    static func make(from rawPayload: ClipPayload) -> CapturedClip? {
        var payload = rawPayload.filter { !$0.isEmpty }
        guard !payload.isEmpty else { return nil }

        // Screenshots often come as both PNG and a much larger TIFF. Keep one.
        payload = payload.map { item in
            var item = item
            if item[PasteboardTypes.png] != nil { item[PasteboardTypes.tiff] = nil }
            return item
        }

        let byteSize = payload.reduce(0) { $0 + $1.values.reduce(0) { $0 + $1.count } }
        guard byteSize > 0, byteSize <= maxBytes else { return nil }

        // Files copied in Finder.
        let fileURLs = payload.compactMap { $0[PasteboardTypes.fileURL] }
            .compactMap { String(data: $0, encoding: .utf8) }
            .compactMap { URL(string: $0) }
        if !fileURLs.isEmpty {
            let names = fileURLs.map { $0.lastPathComponent }
            var title = names[0]
            if names.count > 1 { title += "  +\(names.count - 1) more" }
            return CapturedClip(
                payload: payload, kind: .files, title: title,
                searchText: fileURLs.map(\.path).joined(separator: "\n"),
                hash: sha256("files\n" + fileURLs.map(\.absoluteString).joined(separator: "\n")),
                byteSize: byteSize, fileCount: fileURLs.count,
                isDirectory: fileURLs.count == 1 ? fileURLs[0].hasDirectoryPath : false)
        }

        // Text wins over images: Word, Excel and Pages put a picture of the
        // selection next to the text.
        if let data = payload.first?[PasteboardTypes.text],
           let text = String(data: data, encoding: .utf8) {
            let collapsed = text.split(whereSeparator: \.isWhitespace).joined(separator: " ")
            guard !collapsed.isEmpty else { return nil }
            return CapturedClip(
                payload: payload, kind: .text,
                title: String(collapsed.prefix(maxTitleLength)),
                searchText: String(text.prefix(maxSearchLength)),
                hash: sha256("text\n" + text),
                byteSize: byteSize)
        }

        if let first = payload.first,
           let imageData = PasteboardTypes.images.lazy.compactMap({ first[$0] }).first {
            let size = pixelSize(of: imageData)
            let title = size.map { "Image \($0.width) × \($0.height)" } ?? "Image"
            return CapturedClip(
                payload: payload, kind: .image, title: title, searchText: title,
                hash: sha256(imageData), byteSize: byteSize,
                imageWidth: size?.width, imageHeight: size?.height, imageData: imageData)
        }

        return nil
    }

    static func pixelSize(of data: Data) -> (width: Int, height: Int)? {
        guard let src = CGImageSourceCreateWithData(data as CFData, nil),
              let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any],
              let w = props[kCGImagePropertyPixelWidth] as? Int,
              let h = props[kCGImagePropertyPixelHeight] as? Int else { return nil }
        return (w, h)
    }

    /// Small PNG preview, longest side `maxPixels`.
    static func thumbnailPNG(from data: Data, maxPixels: Int = 120) -> Data? {
        guard let src = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        let opts: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixels,
            kCGImageSourceCreateThumbnailWithTransform: true,
        ]
        guard let cg = CGImageSourceCreateThumbnailAtIndex(src, 0, opts as CFDictionary) else { return nil }
        let out = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(out, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(dest, cg, nil)
        guard CGImageDestinationFinalize(dest) else { return nil }
        return out as Data
    }

    static func sha256(_ string: String) -> String { sha256(Data(string.utf8)) }

    static func sha256(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }
}
